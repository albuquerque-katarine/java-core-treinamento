package bitwise;

public class Programa {

	public static void main(String[] args) {
		
		/*
		 * & AND bit a bit 
		 * | OR bit a bit 
		 * ^ XOR bit a bit 
		 * ~ NOT bit a bit 
		 * << Deslocamento à esquerda 
		 * >> Deslocamento à direita
		 * >>> Deslocamento à direita sem sinal
		 * */
		
		int numero = 8; 
		
		System.out.println(numero << 1);
		System.out.println(numero >> 1);

	}

}
